def _normalize(char: str) -> str:
    upper = char.upper()
    return upper if upper in _GLYPHS else '?'


def glyph(char: str) -> tuple[str, ...]:
    return _GLYPHS[_normalize(char)]


def text_width(text: str, scale: int = 1) -> int:
    """Pixel width including one blank column between glyphs, not after the last."""
    if not text:
        return 0
    return scale * (sum(len(glyph(char)[0]) + 1 for char in text) - 1)


def draw_text(draw: ImageDraw.ImageDraw, xy: tuple[int, int], text: str, fill: int = 255, scale: int = 1) -> int:
    """Draw `text` with its top-left at `xy` and return the x just past it."""
    x, y = xy
    for char in text:
        rows = glyph(char)
        for row_index, row in enumerate(rows):
            for col_index, pixel in enumerate(row):
                if pixel == '#':
                    left = x + col_index * scale
                    top = y + row_index * scale
                    draw.rectangle((left, top, left + scale - 1, top + scale - 1), fill=fill)
        x += (len(rows[0]) + 1) * scale
    return x


def fit(text: str, width: int, scale: int = 1) -> str:
    """Trim `text` so it fits in `width` pixels."""
    while text and text_width(text, scale) > width:
        text = text[:-1]
    return text.rstrip()
